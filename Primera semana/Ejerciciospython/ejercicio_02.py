print("Bienvenido")

numero1 = int(input("Ingrese el primer número: "))
numero2 = int(input("Ingrese el segundo número: "))

if numero1 + numero2 == 10:
    print("La suma de los números es igual a 10.")
else:
    print(f"La suma de los números no es igual a 10. La suma es {numero1 + numero2}.")

if numero1 - numero2 == 10:
    print("La resta de los números es igual a 10.")
else:
    print(f"La resta de los números no es igual a 10. La resta es {numero1 - numero2}.")